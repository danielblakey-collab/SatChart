function permitsFor(d: string, districtKey: string): number {
  const row = permitsByDate[d];
  if (!row) return 0;
  switch (districtKey) {
    case "naknek-kvichak": return row.nk;
    case "egegik": return row.e;
    case "ugashik": return row.u;
    case "nushagak": return row.n;
    case "togiak": return row.t;
    default: return 0;
  }
}

function mkOps(
  year: number,
  date: string,
  districtKey: "naknek-kvichak" | "egegik" | "ugashik" | "nushagak" | "togiak",
  driftOpenHours: number,
  setOpenHours: number,
  totalCatch: number | null,
  notes?: string[]
) {
  const driftPermits = permitsFor(date, districtKey);
  const dualPermits = 0;
  const driftBoats = driftPermits; // no dual column in 2012 Table 15
  return {
    year,
    date,
    districtKey,
    driftOpenHours,
    setOpenHours,
    driftPermits,
    dualPermits,
    driftBoats,
    catch: { total: totalCatch },
    ...(notes ? { notes } : {}),
  };
}

